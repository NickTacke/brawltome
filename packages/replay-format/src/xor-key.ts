// BMG's XOR obfuscation key. May rotate on future patches; envelope falls back to null on mismatch.
export const XOR_KEY = new Uint8Array([
  0x6b, 0x10, 0xde, 0x3c, 0x44, 0x4b, 0xd1, 0x46, 0xa0, 0x10, 0x52, 0xc1, 0xb2, 0x31, 0xd3, 0x6a, 0xfb, 0xac, 0x11,
  0xde, 0x06, 0x68, 0x08, 0x78, 0x8c, 0xd5, 0xb3, 0xf9, 0x6a, 0x40, 0xd6, 0x13, 0x0c, 0xae, 0x9d, 0xc5, 0xd4, 0x6b,
  0x54, 0x72, 0xfc, 0x57, 0x5d, 0x1a, 0x06, 0x73, 0xc2, 0x51, 0x4b, 0xb0, 0xc9, 0x8c, 0x78, 0x04, 0x11, 0x7a, 0xef,
  0x74, 0x3e, 0x46, 0x39, 0xa0, 0xc7, 0xa6,
])

export function applyXor(data: Uint8Array): Uint8Array {
  const out = new Uint8Array(data.length)
  for (let i = 0; i < data.length; i++) {
    out[i] = data[i] ^ XOR_KEY[i % XOR_KEY.length]
  }
  return out
}
