#!/usr/bin/env bun
// Generates packages/game-data/src/generated/statLadders.ts and physics.ts
// from the decrypted Brawlhalla SWZ dumps.
//
// Source of truth:
//   - Game.swz.52.xml : StatType ladder definitions (Speed0-11, Strength0-11,
//     Weight0-11, Dexterity0-11 + Template baseline).
//   - Game.swz.23.xml : HeroTypes (per-legend stat signature).
//
// The repo's own ingest.ts cannot reach these files (research/swz-extract/out
// is not committed), so this script consumes the decrypted dumps directly and
// commits the generated output, matching the repo's committed-generated pattern.

import { readFileSync, writeFileSync } from 'node:fs'
import type { Legend, LegendPhysics, StatLadder } from '../src/types'

const DECRYPTED = new URL('../../../research/brawlhalla-physics/decrypted/', import.meta.url)
const OUT_DIR = new URL('../src/generated/', import.meta.url).pathname

// --- Stat ladders (Game.swz.52.xml) --------------------------------------

function extractStatLadders(): StatLadder[] {
  const xml = readFileSync(new URL('Game.swz.52.xml', DECRYPTED), 'utf8')
  const ladders: StatLadder[] = []
  const open = /<StatType\s+StatName="([^"]*)">/g
  let m: RegExpExecArray | null
  while ((m = open.exec(xml)) !== null) {
    const name = m[1]
    const start = m.index + m[0].length
    const closeIdx = xml.indexOf('</StatType>', start)
    const body = xml.slice(start, closeIdx === -1 ? undefined : closeIdx)
    const values: Record<string, number> = {}
    const fieldRe = /<(\w+)>([^<]*)<\/\1>/g
    let f: RegExpExecArray | null
    while ((f = fieldRe.exec(body)) !== null) {
      const n = Number(f[2])
      if (Number.isFinite(n)) values[f[1]] = n
    }
    ladders.push({ statName: name, values })
  }
  return ladders
}

// --- Legends (Game.swz.23.xml) --------------------------------------------

function extractLegends(): Legend[] {
  const xml = readFileSync(new URL('Game.swz.23.xml', DECRYPTED), 'utf8')
  const open = /<HeroType\s+HeroName="([^"]*)">/g
  const legends: Legend[] = []
  let m: RegExpExecArray | null
  while ((m = open.exec(xml)) !== null) {
    const heroName = m[1]
    const start = m.index + m[0].length
    const closeIdx = xml.indexOf('</HeroType>', start)
    const body = xml.slice(start, closeIdx === -1 ? undefined : closeIdx)
    const field = (n: string) => {
      const f = body.match(new RegExp(`<${n}>([^<]*)</${n}>`))
      return f ? f[1] : ''
    }
    if (!heroName || heroName === 'Template') continue
    const num = (n: string) => {
      const v = field(n)
      const x = Number(v)
      return Number.isFinite(x) ? x : 0
    }
    legends.push({
      heroId: num('HeroID'),
      heroName,
      displayName: field('HeroDisplayName'),
      strength: num('Strength'),
      dexterity: num('Dexterity'),
      weight: num('Weight'),
      speed: num('Speed'),
      weaponOne: field('BaseWeapon1'),
      weaponTwo: field('BaseWeapon2'),
      isActive: /^true$/i.test(field('IsActive')),
      isBeta: /^true$/i.test(field('IsBeta')),
    })
  }
  return legends
}

// --- Physics resolution ----------------------------------------------------

function buildPhysics(legends: Legend[], ladders: StatLadder[]): LegendPhysics[] {
  const byName = new Map(ladders.map((l) => [l.statName, l]))
  const get = (ladder: string, field: string): number => byName.get(ladder)?.values[field] ?? 0
  return legends
    .filter((l) => l.heroId > 0)
    .map((l) => ({
      heroId: l.heroId,
      stats: { strength: l.strength, dexterity: l.dexterity, weight: l.weight, speed: l.speed },
      physics: {
        impulseMult: get(`Strength${l.strength}`, 'ImpulseMult'),
        recovery: get(`Weight${l.weight}`, 'Recovery'),
        runSpeed: get(`Speed${l.speed}`, 'RunSpeed'),
        jumpXImpulse: get(`Speed${l.speed}`, 'JumpXImpulse'),
        acceleration: get(`Speed${l.speed}`, 'Acceleration'),
        friction: get(`Speed${l.speed}`, 'Friction'),
        airRunSpeed: get(`Speed${l.speed}`, 'AirRunSpeed'),
        airAcceleration: get(`Speed${l.speed}`, 'AirAcceleration'),
        airFriction: get(`Speed${l.speed}`, 'AirFriction'),
        recoverMod: get(`Dexterity${l.dexterity}`, 'RecoverMod'),
        sigRecoverMod: get(`Dexterity${l.dexterity}`, 'SigRecoverMod'),
        minChargeMod: get(`Dexterity${l.dexterity}`, 'MinChargeMod'),
        durabilityMod: get(`Dexterity${l.dexterity}`, 'DurabilityMod'),
      },
    }))
    .sort((a, b) => a.heroId - b.heroId)
}

function emit<T>(name: string, values: T[], typeName: string) {
  const body = `// @generated by packages/game-data/scripts/generate-physics.ts - do not edit.\nimport type { ${typeName} } from '../types'\n\nconst data = ${JSON.stringify(values, null, 2)} as const\n\nexport const ${name}: readonly ${typeName}[] = data as unknown as readonly ${typeName}[]\n`
  writeFileSync(`${OUT_DIR}${name}.ts`, body)
  console.log(`wrote ${name}.ts  (${values.length} rows)`)
}

const ladders = extractStatLadders()
const legends = extractLegends()
const physics = buildPhysics(legends, ladders)

emit('statLadders', ladders, 'StatLadder')
emit('physics', physics, 'LegendPhysics')
console.log(`ladders=${ladders.length} legends=${legends.length} physics=${physics.length}`)
