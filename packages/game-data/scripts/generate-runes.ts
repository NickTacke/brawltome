#!/usr/bin/env bun
// Generates packages/game-data/src/generated/runes.ts from Game.swz.42.xml (RuneTypes).
// RuneTypes = the COMPLETE per-legend stance/loadout table: every legend has 10
// runes (0=Base, 1-4=Speed/Strength/Weight/Dexterity, 5-8=Super variants, 9=Challenge),
// each with absolute S/D/W/Sp stat values. This is what the game client uses to
// display stances in the UI, and what the replay stanceIndex references.
import { readFileSync, writeFileSync } from 'node:fs'

const DECRYPTED = new URL('../../../research/brawlhalla-physics/decrypted/', import.meta.url)
const OUT_DIR = new URL('../src/generated/', import.meta.url).pathname

const xml = readFileSync(new URL('Game.swz.42.xml', DECRYPTED), 'utf8')

type Rune = {
  heroName: string
  runeIndex: number
  strength: number
  dexterity: number
  weight: number
  speed: number
  iconName: string
}

const runes: Rune[] = []
const heroRe = /<RuneType>(.*?)<\/RuneType>/g
let m: RegExpExecArray | null
let curHero = ''
while ((m = heroRe.exec(xml)) !== null) {
  const body = m[1]
  const field = (n: string) => {
    const f = body.match(new RegExp(`<${n}>([^<]*)</${n}>`))
    return f ? f[1] : ''
  }
  const hn = field('HeroName')
  if (hn) curHero = hn
  if (!curHero) continue
  const num = (n: string) => {
    const v = Number(field(n))
    return Number.isFinite(v) ? v : -1
  }
  runes.push({
    heroName: curHero,
    runeIndex: num('RuneIndex'),
    strength: num('Strength'),
    dexterity: num('Dexterity'),
    weight: num('Weight'),
    speed: num('Speed'),
    iconName: field('IconName'),
  })
}

const body = `// @generated by packages/game-data/scripts/generate-runes.ts - do not edit.\n// Source: Game.swz.42.xml (RuneTypes) — full per-legend stance loadout table.\nexport type Rune = {\n  heroName: string\n  runeIndex: number\n  strength: number\n  dexterity: number\n  weight: number\n  speed: number\n  iconName: string\n}\n\nconst data = ${JSON.stringify(runes, null, 2)} as const\n\nexport const runes: readonly Rune[] = data as unknown as readonly Rune[]\n`
writeFileSync(`${OUT_DIR}runes.ts`, body)
console.log(`wrote runes.ts (${runes.length} records, ${new Set(runes.map((r) => r.heroName)).size} heroes)`)
